"use client";

import { useEffect } from "react";
import { usePathname } from "next/navigation";

// ============================================================
// ثبتِ سرویس‌ورکر (PWA)
// ============================================================
// همتای frontend/js/common.js:873. در نسخه‌ی Next هیچ‌جا ثبت نمی‌شد، یعنی:
//
//   • سایت روی گوشی «نصب‌شدنی» نبود، هرچند manifest سرِ جایش بود.
//   • rewriteهای /sw.js و /offline.html در next.config.ts بی‌مصرف بودند —
//     یعنی وقتی اینترنتِ مشتری قطع می‌شد، به‌جای صفحه‌ی فارسیِ خودمان صفحه‌ی
//     خشکِ «Site can't be reached» مرورگر را می‌دید. دقیقاً همان چیزی که
//     offline.html برای جلوگیری از آن نوشته شده بود.
//
// خودِ sw.js برای این مبدأ هم بی‌خطر است: ناوبری‌ها همیشه از شبکه می‌آیند و
// فقط در catch به صفحه‌ی آفلاین می‌افتند، و از دارایی‌ها فقط فونت و آیکون کش
// می‌شود. هیچ صفحه، قیمت یا پاسخِ APIای کش نمی‌شود، پس خطرِ نشان‌دادنِ قیمتِ
// کهنه وجود ندارد.
//
// چرا /admin مستثنا است: عیناً همان قاعده‌ی نسخه‌ی Express. پنل ابزارِ کار
// است نه اپلیکیشنِ نصب‌شدنی، و لایه‌ی کشِ اضافه فقط می‌تواند مدیر را گمراه
// کند. توجه: دامنه‌ی سرویس‌ورکر `/` است، پس اگر پیش‌تر در صفحه‌ای دیگر ثبت
// شده باشد روی /admin هم فعال می‌ماند — این شرط فقط جلوی *ثبتِ* تازه را
// می‌گیرد، همان‌طور که در common.js هم همین بود.

export function ServiceWorkerRegistrar() {
  const pathname = usePathname();

  useEffect(() => {
    if (!("serviceWorker" in navigator)) return;
    if (pathname?.startsWith("/admin")) return;
    // ثبت اختیاری است: اگر مرورگر یا شرایط اجازه نداد (مثلاً HTTP روی
    // میزبانی غیرِ localhost) سایت باید عادی کار کند، نه اینکه خطا بدهد.
    navigator.serviceWorker.register("/sw.js").catch(() => {});
  }, [pathname]);

  return null;
}
