"use client";

import { useEffect, useState } from "react";
import type { CSSProperties, MouseEvent } from "react";
import { reloadPage } from "@/lib/navigation";

// ============================================================
// «این صفحه چرا باز نمی‌شود؟» — هشدارِ بارگذاریِ معلّق
// ============================================================
// تا امروز بارگذاری **بی‌زبان** بود: اسکلتونِ نبض‌دار یا یک چرخِ کوچک، بی‌نهایت.
// اگر آن انتظار هیچ‌وقت تمام نمی‌شد — بک‌اند خواب، اینترنتِ کند، یا ناوبریِ
// گیرکرده — مشتری تا ابد به همان اسکلتون نگاه می‌کرد و **هیچ راهی برای بیرون
// آمدن نداشت**: نه پیامی، نه دکمه‌ای، نه لینکی. بدترین جایش مسیرِ ورود است:
// کسی که همین حالا کد ورود را زده و منتظرِ صفحه‌ی سفارشش است.
//
// این کامپوننت سکوت را می‌شکند، ولی **دو نیمه** دارد که عمداً از هم جدا شده‌اند:
//
//   ۱) نیمه‌ی دیداری = CSS (`.stall-notice` در `src/app/globals.css`).
//      دلیلش تجربی است، نه سلیقه‌ای: در یک بارگذاریِ کاملِ سند، این پیام برای
//      مرورگر HTMLِ خام و استریم‌شده است که در یک مرزِ معلّق نگه داشته شده و
//      React تا نرسیدنِ محتوا **hydrate‌ش نمی‌کند** — پس هیچ effectی داخلش
//      اجرا نمی‌شود. (با بک‌اندِ خواب، در مرورگر اندازه‌گیری شد: اسکلتون دیده
//      می‌شد و تایمرهای همین کامپوننت هرگز اجرا نشدند.) گاردی که نمایشش را به
//      effect بسپارد، دقیقاً در همان حالتی که برایش ساخته شده کاری نمی‌کند.
//      پس نمایش را مرورگر با یک `animation-delay` انجام می‌دهد: هر جا این HTML
//      برسد، پیام سرِ وقتش می‌آید — با یا بی‌hydration.
//
//   ۲) نیمه‌ی جاوااسکریپتی = فقط کارهایی که CSS نمی‌تواند: اعلام به صفحه‌خوان
//      (چون پیام از اول در DOM است و با `visibility: hidden` پنهان می‌شود،
//      ناحیه‌ی زنده‌ی جداگانه‌ای لازم است که سرِ وقت پر شود) و ارتقای دکمه‌ی
//      «بارگذاری دوباره» به یک ناوبریِ صریح در `lib/navigation.ts`. اگر این
//      نیمه هرگز اجرا نشود، هر دو راهِ فرار همچنان کار می‌کنند چون `<a>` هستند.
//
// و هیچ‌کدام ناوبریِ در جریان را لغو نمی‌کنند: این پیام بخشی از همان مرزِ
// بارگذاری است؛ لحظه‌ای که محتوای واقعی برسد، مرز برداشته می‌شود و پیام هم با
// آن می‌رود. پس هیچ‌وقت جای صفحه‌ی سالم را نمی‌گیرد.

/**
 * چند ثانیه بی‌خبری یعنی «گیر کرده»؟
 *
 * ۶ ثانیه انتخاب شد چون هر انتظارِ واقعیِ این پروژه کوتاه‌تر از آن است:
 * بررسیِ نشست در middleware سقفِ ۲٫۵ ثانیه دارد و صفحه‌های سبکِ بعد از ورود
 * (سفارش، حساب، پرداخت) زیر یک ثانیه تمام می‌شوند. از آن طرف، سقفِ خودِ
 * درخواست‌های API ۱۵ ثانیه است — یعنی بدونِ این پیام، کاربر تا ۹ ثانیه‌ی
 * اضافه هم فقط مستطیلِ نبض‌دار می‌دید و هیچ چیزِ دیگری.
 */
export const STALL_NOTICE_MS = 6000;

// متن‌ها یک جا: CSS، آزمون و صفحه‌خوان باید همیشه یک چیز بگویند.
const HEADLINE = "این صفحه دارد دیر باز می‌شود";
const EXPLANATION =
  "احتمالاً سرور یا اینترنت کند شده. سبد و سفارش‌های شما سر جای خودشان هستند؛ اگر وارد شده‌اید، ورودتان ثبت شده است.";
const RELOAD_LABEL = "بارگذاری دوباره";
const HOME_LABEL = "صفحه‌ی اصلی";

/** دکمه‌ی سبزِ گرد — برای هر دو راهِ فرار، یکی پر و یکی تُوخالی */
const ESCAPE_BASE =
  "inline-flex items-center rounded-full px-5 py-2 text-xs font-bold transition-colors";

export function StallNotice({
  delayMs = STALL_NOTICE_MS,
}: {
  delayMs?: number;
}) {
  const [announced, setAnnounced] = useState(false);

  useEffect(() => {
    // فقط اعلامِ صفحه‌خوان. نمایشِ دیداری کارِ CSS است (توضیحِ بالای فایل)،
    // پس اگر همین effect هرگز اجرا نشود کاربرِ بینا پیام و راهِ فرارش را
    // می‌بیند.
    const timer = setTimeout(() => setAnnounced(true), delayMs);
    return () => clearTimeout(timer);
  }, [delayMs]);

  function handleReload(event: MouseEvent<HTMLAnchorElement>) {
    // اگر جاوااسکریپت زنده است، بارگذاریِ صریح (همان کاری که کاربر می‌خواهد)؛
    // اگر نه، خودِ `href=""` کارِ مرورگر را می‌کند: پیمایش به همان آدرسِ فعلی.
    event.preventDefault();
    reloadPage();
  }

  return (
    <>
      {/*
        ناحیه‌ی زنده‌ی خالی — از همان اول در DOM است تا وقتی متن داخلش
        می‌ریزد، صفحه‌خوان آن را *اعلام* کند. اگر خودِ ناحیه را سرِ مهلت
        می‌ساختیم، درجِ یک ناحیه‌ی زنده‌ی تازه تقریباً هیچ‌وقت اعلام نمی‌شود.
        قبل از مهلت خالی است، پس مشتری هیچ‌وقت بی‌دلیل چیزی نمی‌شنود.
      */}
      <p className="sr-only" role="status" aria-live="polite">
        {announced ? `${HEADLINE} — ${RELOAD_LABEL}` : ""}
      </p>

      <div
        // کلاسِ `stall-notice` نمایشِ تأخیری را به عهده دارد: تا مهلت، نه
        // دیده می‌شود و نه در درختِ صفحه‌خوان هست (`visibility: hidden`).
        className="stall-notice mx-auto mt-2 max-w-[420px] rounded-2xl px-6 py-5 text-center"
        style={
          {
            background: "var(--color-surface)",
            border: "1px solid var(--color-line)",
            // همان متغیری که قانونِ `.stall-notice` می‌خواند. یک جا تعریف
            // می‌شود تا عددِ کامپوننت و عددِ CSS از هم جدا نیفتند.
            "--stall-delay": `${delayMs}ms`,
          } as CSSProperties
        }
      >
        <p
          className="text-sm font-bold mb-1.5"
          style={{ color: "var(--color-ink)" }}
        >
          {HEADLINE}
        </p>
        <p
          className="text-xs leading-relaxed mb-4"
          style={{ color: "var(--color-ink-soft)" }}
        >
          {EXPLANATION}
        </p>

        <div className="flex flex-wrap justify-center gap-2">
          {/*
            `href=""` = پیمایش به همان آدرسِ فعلی، یعنی «بارگذاری دوباره».
            عمداً یک لینکِ ساده است و نه <button>: اگر hydration انجام نشود،
            هیچ onClickای نیست، ولی خودِ مرورگر بارگذاری را انجام می‌دهد.
          */}
          <a
            href=""
            onClick={handleReload}
            className={ESCAPE_BASE}
            style={{ background: "var(--color-teal)", color: "#04211B" }}
          >
            {RELOAD_LABEL}
          </a>
          {/*
            عمداً <a> و نه <Link>: این دکمه وقتی لازم می‌شود که روترِ Next
            نتوانسته کارش را بکند. لینکی که به همان روتر وابسته باشد، دقیقاً
            همان چیزی است که دارد کار نمی‌کند.
          */}
          {/* eslint-disable-next-line @next/next/no-html-link-for-pages */}
          <a
            href="/"
            className={ESCAPE_BASE}
            style={{
              border: "1px solid var(--color-line)",
              color: "var(--color-ink)",
            }}
          >
            {HOME_LABEL}
          </a>
        </div>
      </div>
    </>
  );
}
