// ============================================================
// نوارِ متحرکِ اعتماد — همتای `div.marquee` در `frontend/index.html`
// ============================================================
// نسخهٔ Express یک نوارِ بی‌پایان با شش وعدهٔ فروشگاه است که بینِ هیرو و
// دسته‌بندی‌ها می‌نشیند. در Next اصلاً نیامده بود؛ یعنی صفحهٔ اصلی شش جملهٔ
// اعتمادساز را نداشت که Express داشت — و همین در گزارشِ برابری به‌عنوان
// بدهیِ بازِ متن ثبت شده بود.
//
// دو نکتهٔ پیاده‌سازی:
//   • متن **شش بار** تکرار می‌شود و پلهٔ انیمیشن یک نسخه است
//     (`translateX(calc(100% / 6))` در globals.css) — حلقهٔ بی‌درز.
//     چرا شش و نه دو: نوار `display:flex` است و صفحه RTL، پس لبهٔ لنگرِ
//     نوارِ درونی همان لبهٔ راستِ ظرف است و انیمیشن به راست حرکت می‌کند.
//     با دو نسخه، تا انتهای نیم‌سیکل لبهٔ چپِ نوار = (عرضِ ظرف − عرضِ یک
//     نسخه) است؛ اگر عرضِ یک نسخه از عرضِ ظرف کمتر باشد (C < W — روی هر
//     نمایشگری پهن‌تر از ~۱۰۰۰px) سمتِ چپ **فاصلهٔ خالی** می‌دهد. شرطِ
//     بی‌فاصله‌بودن در هر لحظه (N−1)×C ≥ W است؛ با شش نسخه تا W ≈ ۵×C
//     (اندازه‌گیری‌شده: ~۵۰۸۰px) پر می‌ماند. نگهبانِ هندسی همین شرط را در e2e می‌سنجد.
//   • `aria-hidden` چون تزئینی است و همان حرف‌ها در بخش‌های دیگر صفحه با
//     اسکرین‌ریدر خوانده می‌شوند؛ نوارِ متحرک پشتِ سرِ خواننده تکرار نشود.

const ITEMS = [
  "ارسال سریع به سراسر کشور",
  "پرداخت امن زرین‌پال",
  "ضمانت اصالت کالا",
  "۷ روز مهلت مرجوعی",
  "مشاوره‌ی صادقانه",
  "قیمت منصفانه",
];

export function Marquee() {
  return (
    <div className="marquee" aria-hidden="true">
      <div className="marquee-track">
        {/* شش نسخهٔ یکسان برای حلقهٔ بی‌درز — تعداد باید با پلهٔ `100%/N`ِ
            keyframes در globals.css یکی بماند (نگهبانِ هندسی در e2e). */}
        {[0, 1, 2, 3, 4, 5].map((copy) => (
          <span key={copy}>
            {ITEMS.map((item) => (
              <span key={item} className="marquee-item">
                {item} <b>✦</b>
              </span>
            ))}
          </span>
        ))}
      </div>
    </div>
  );
}
