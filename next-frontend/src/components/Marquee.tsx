  "قیمت منصفانه",
  // هشت قلمِ تازه (درخواستِ کارفرما: «کلماتِ تکراری نه، کلماتِ جدید»). چرا
  // لازم بود: با شش قلم، یک نسخه ~۱۰۱۶px است و در هر پاسِ صفحه همان شش جمله
  // دوباره دیده می‌شد — «تکراری». با ۱۴ قلم یک نسخه ~۲۳۰۰px می‌شود؛ چشمِ
  // بینندهٔ یک نمایشگر ~۸ قلمِ متفاوت می‌بیند و تکرار دیر به چشم می‌آید.
  // هر قلم باید *واقعی* باشد — چند تا اسمِ دسته‌های خودِ فروشگاه است، نه وعدهٔ
  // توخالی. (کامنتِ نو، اما بدون هیچ لنگر جهش — `copyParity` فقط شش قلمِ
  // اوراکل را می‌پاید و این هشت قلم از منبعِ دیگری می‌آیند.)
  "بسته‌بندی محکم و ایمن",
