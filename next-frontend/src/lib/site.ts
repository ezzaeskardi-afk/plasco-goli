// ============================================================
// پایه‌ی درخواست‌های API
// ============================================================
// این تابع عمداً به `typeof window` نگاه می‌کند و نه به یک متغیرِ محیطی:
//
//   • در مرورگر رشته‌ی خالی برمی‌گردد، یعنی مسیرِ نسبی. درخواست به مبدأِ خودِ
//     Next می‌رود و `rewrites` در next.config.ts آن را به Express می‌دهد.
//     نتیجه: هم‌مبدأ می‌شود، پس کوکیِ نشست (`polasco.sid`) همراه می‌رود و
//     سدِ CSRFِ Express هم راضی است.
//
//   • روی سرور آدرسِ مطلق لازم است، چون fetchِ Node مبدأ ندارد و مسیرِ نسبی
//     را نمی‌فهمد.
//
// اگر اینجا در مرورگر آدرسِ مطلقِ :3000 برگردانده شود (کاری که قبلاً
// می‌شد) هر درخواست cross-origin می‌شود: Express هیچ هدرِ CORS نمی‌دهد، کوکی
// فرستاده نمی‌شود، و هر «نوشتن» با ۴۰۳ رد می‌شود.
export function apiBase(): string {
  if (typeof window !== "undefined") return "";
  return (process.env.API_ORIGIN || "http://localhost:3000").replace(/\/+$/, "");
}
