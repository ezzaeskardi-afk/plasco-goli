/**
 * مسیرِ عکسِ محصول، تضمین‌شده «دقیقاً یک‌بار کدشده».
 *
 * داستانِ این تابع یک باگِ واقعی است: API مقدارِ `image` را **از قبل**
 * percent-encoded برمی‌گرداند
 *
 *     /picture/products/%D8%B3%D8%B7%D9%84%20….jpg
 *
 * و هم Express و هم پرتِ اولیهٔ Next دوباره `encodeURI` روی آن می‌زدند. نتیجه
 * `%25D8…` بود؛ یعنی عکسی که معرفی می‌شد **۴۰۴** می‌داد (سنجیده شد: همان
 * نشانی روی :3000 و :3001 هر دو ۴۰۴ بودند). این در og:image، در `image` داده‌ی
 * ساختاریافته و در `<image:loc>` نقشه‌ی سایت تکرار شده بود — یعنی دقیقاً
 * همان جاهایی که باید عکسِ محصول را به گوگل و واتساپ معرفی کنند.
 *
 * الگوریتم یک تله دارد که با اندازه‌گیری پیدا شد: `encodeURI` خودش `%` را هم
 * به `%25` تبدیل می‌کند، پس «یک‌بار decode، یک‌بار encode» هیچ‌وقت نمی‌تواند
 * بفهمد ورودی دوبار‌کدشده بوده یا نه (`encodeURI(decodeURI(x)) === x` برای هر
 * دو حالتِ یک‌بار و دوبار‌کدشده درست است). پس امضای دقیقِ دوبار‌کدشدگی — یعنی
 * `%25` که بلافاصله یک جفت رقمِ هگز دارد (`%25D8`) — علامتِ کار گرفته می‌شود:
 *
 *   ۱) دوبار‌کدشده؟ یک لایه رمزگشایی و تمام (`%25D8` → `%D8`).
 *   ۲) از قبل کدشده؟ دست نزن.
 *   ۳) خام؟ یک‌بار کد کن.
 *
 * هزینهٔ این تشخیص: فایلی که *واقعاً* در نامش `%25` و بعدش دو رقمِ هگز داشته
 * باشد (یعنی خودِ نام شاملِ `%D8` باشد) یک لایه اشتباه رمزگشایی می‌شود. چنین
 * نامی در این پروژه وجود ندارد — نام‌ها از آپلود می‌آیند و اینجا `image` از
 * قبل کدشده است — در حالی که نشانیِ دوبار‌کدشده یک وضعیتِ واقعیِ گذشته است
 * (همین باگ، در og:image و JSON-LD و نقشه‌ی سایت).
 *
 * تنها استثنای دیگر: فایل‌هایی که خودشان `/` یا `?` یا `#` کدشده دارند؛
 * `decodeURI` آن‌ها را باز نمی‌کند (چون نویسه‌های رزروشده‌اند) پس دوباره کد
 * می‌شوند. چنین نامی در این پروژه وجود ندارد.
 */
export function publicImagePath(raw: string | null | undefined): string {
  if (!raw) return "";

  // حالت ۱: امضای دوبار‌کدشدگی.
  if (/%25[0-9A-Fa-f]{2}/.test(raw)) {
    try {
      return decodeURI(raw);
    } catch {
      /* یک لایهٔ دومِ سالم نداشت — مثل خام رفتار می‌شود */
    }
  }

  // حالت ۲: از قبل یک‌بار کدشده است.
  if (/%[0-9A-Fa-f]{2}/.test(raw)) return raw;

  // حالت ۳: خام.
  try {
    return encodeURI(raw);
  } catch {
    // `%` تنها و نامعتبر (نامِ فایلی که خودش `%` دارد)
    return raw;
  }
}

