// ============================================================
// سالِ پاورقی — نگهبانِ «هیچ‌وقت عقب نماند»
// ============================================================
// باگی که این آزمون برای جلوگیری از بازگشتش نوشته شده، واقعی و امروز دیده شد:
// پاورقی نسخه‌ی Next «© ۱۴۰۴» را دستی نوشته بود و در شهریورِ ۱۴۰۵ یک سال عقب
// بود. نسخه‌ی Express سال را در مرورگر حساب می‌کرد (`initFooterYear`)، پس
// هرگز عقب نمی‌ماند.

import { describe, expect, it } from "vitest";
import { footerNotice, jalaliYear } from "@/lib/jalaliYear";

const FA_DIGITS = /^[۰-۹]+$/;

describe("jalaliYear — سالِ شمسی با رقم‌های فارسی", () => {
  it("سالِ میلادیِ ۲۰۲۶ را ۱۴۰۵ می‌دهد (نه ۲۰۲۶ لاتین)", () => {
    // ۲۹ سپتامبر ۲۰۲۶ = ۷ مهر ۱۴۰۵
    expect(jalaliYear(new Date("2026-09-29T12:00:00Z"))).toBe("۱۴۰۵");
  });

  it("نیمه‌ی دومِ سالِ میلادی هنوز سالِ شمسیِ بعدی نیست", () => {
    // مرزِ سالِ شمسی حدودِ ۲۱ مارس است؛ این آزمون همان مرز را از یک طرف می‌گیرد.
    expect(jalaliYear(new Date("2026-03-20T12:00:00Z"))).toBe("۱۴۰۴");
    expect(jalaliYear(new Date("2026-03-22T12:00:00Z"))).toBe("۱۴۰۵");
  });

  it("همیشه با رقم‌های فارسی برمی‌گردد، نه لاتین", () => {
    for (const iso of ["2024-01-01", "2026-06-15", "2030-12-31"]) {
      const year = jalaliYear(new Date(`${iso}T12:00:00Z`));
      expect(year, iso).toMatch(FA_DIGITS);
    }
  });

  it("متنِ پاورقی سال را در خود دارد و «©» را نگه می‌دارد", () => {
    const text = footerNotice(new Date("2026-09-29T12:00:00Z"));
    expect(text).toContain("۱۴۰۵");
    expect(text).toContain("پلاسکو گلی");
    expect(text.startsWith("©")).toBe(true);
  });

  it("هرگز یک سالِ ثابت نیست — سالِ بعدی فرق می‌کند", () => {
    // ساده‌ترین راهِ گرفتنِ «سالِ دستی‌نوشته»: دو تاریخِ یک‌سال‌فاصله باید دو
    // خروجیِ متفاوت بدهند. با یک رشته‌ی ثابت در کد، این آزمون قرمز می‌شود.
    expect(jalaliYear(new Date("2026-09-29T12:00:00Z"))).not.toBe(
      jalaliYear(new Date("2027-09-29T12:00:00Z")),
    );
  });
});
