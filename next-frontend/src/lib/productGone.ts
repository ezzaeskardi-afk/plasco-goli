// ============================================================
// «محصولِ حذف‌شده» — تشخیصِ مسیر و کشِ کوتاه‌عمرِ وجودِ محصول
// ============================================================
// ---------- چرا این ماژول جدا است ----------
// `middleware.ts` در محیطِ Edge اجرا می‌شود و `next/server` را می‌خواهد، پس
// مستقیماً در Vitest قابلِ ایمپورت نیست. این ماژول هیچ وابستگی‌ای ندارد، پس
// همان تصمیم‌های منطقی این‌جا سنجیده می‌شود و middleware فقط نتیجه را به یک
// پاسخِ HTTP تبدیل می‌کند — همان الگویی که `legacyUrls.ts` برای نگاشتِ
// نشانی‌های عصرِ Express دارد.
//
// ---------- چرا اصلاً لازم شد ----------
// نسخه‌ی Express برای محصولِ ناموجود کدِ **۴۱۰** می‌دهد (`server.js:526`). در
// Next مسیرِ `/product/[id]` هم پر‌رندر (ISR) است و پاسخِ `notFound()` را هم
// به‌عنوان HTMLِ کش‌شده با کدِ **۲۰۰** برمی‌گرداند — یعنی یک soft-404 که به
// گوگل می‌گوید «این صفحه سالم است». نبودِ `meta robots` هم سابقاً همین را
// می‌گفت. `generateMetadata` بخشی از آسیب را گرفت (noindex شد)، ولی کدِ وضعیت
// با هیچ تنظیمی از سمتِ صفحه قابلِ تغییر نیست: در App Router نه `page.tsx` و نه
// `not-found.tsx` نمی‌توانند کدِ دلخواه بگذارند.
//
// پس تصمیم در لایه‌ی middleware گرفته می‌شود: یک نگاهِ کوتاه‌عمر می‌پرسد «این
// شناسه محصول دارد؟» و اگر ندارد، صفحه‌ی حذف با کدِ ۴۱۰ برگردانده می‌شود.

/**
 * الگویِ مسیرِ صفحهٔ محصول — یک جعبهٔ تنها برای هر دو تابع.
 *
 * عمداً یک regex است و نه دو تابع با برشِ رشته: `internalLinks.test.ts` هر
 * رشتهٔ نقل‌قولی را که با `/` شروع شود «آدرس» می‌شمارد و اگر این‌جا تکه‌ی
 * `"/product/"` می‌نوشتیم، نگهبانِ پیوندهای داخلی آن را یک ارجاعِ دقیق
 * می‌دید که هیچ مسیری به آن نمی‌رسد (درست هم می‌دید: آن تکه خودش مقصد نیست).
 */
const PRODUCT_PATH = /^\/product\/([^/]+)$/;

/** آیا این مسیر، صفحهٔ یک محصول است؟ (`/product/123`، `/product/abc`) */
export function isProductPath(pathname: string): boolean {
  return PRODUCT_PATH.test(pathname);
}

/** شناسهٔ خامِ محصول از مسیرِ `/product/:id` (بدونِ اعتبارسنجیِ عددی)، یا null. */
export function productIdFromPath(pathname: string): string | null {
  const m = PRODUCT_PATH.exec(pathname);
  return m ? m[1] : null;
}

/**
 * از کدِ پاسخِ `GET /api/products/:id`، «آیا این محصول وجود دارد؟» را می‌سازد.
 *
 * چرا این تابع جدا و آزموده است: قاعده‌اش یک نکته‌ی غیرِشهودی دارد. سرور برای
 * شناسه‌ی نامعتبر کدِ **۴۰۰** می‌دهد («شناسهٔ محصول معتبر نیست»)، نه ۴۰۴ — و
 * Express هم برای همان مسیر ۴۱۰ می‌داد. اگر فقط ۴۰۴ را «نبودن» بشماریم،
 * `/product/abc` بی‌صدا به همان ۲۰۰ِ soft-404 برمی‌گردد و هیچ تستِ دیگری این
 * را نمی‌گیرد.
 *
 * هر نتیجه‌ی دیگری — از جمله ۵xx و `0` (خطای شبکه، چون `fetch` کد نمی‌دهد) —
 * «هست» حساب می‌شود: اگر بک‌ند خواب باشد بهتر است صفحه‌ی محصول باز شود تا
 * اینکه کلِ فروشگاه ۴۱۰ بگیرد.
 */
export function existsFromApiStatus(status: number): boolean {
  return status !== 404 && status !== 400;
}

export interface ExistenceCache {
  get(id: string, now?: number): boolean | undefined;
  set(id: string, exists: boolean, now?: number): void;
  size(): number;
  clear(): void;
}

/**
 * کشِ «آیا این شناسه واقعاً محصول دارد؟».
 *
 * ---------- چرا کش لازم است ----------
 * بدونِ کش، **هر** بازدیدِ صفحه‌ی محصول یک درخواستِ اضافه به API می‌زند؛ یعنی
 * پرارزش‌ترین صفحهٔ فروشگاه کند می‌شود تا صفحه‌ی حذف‌شده‌ها کدِ درست بگیرند —
 * معامله‌ی بدی است. با کش، هزینه فقط بارِ اولِ هر شناسه است و بعدش یک نگاه در
 * حافظه. چون فروشگاه ده‌ها محصول دارد، در عمل بعد از چند دقیقه همه چیز گرم
 * است.
 *
 * ---------- چرا TTL کوتاه است ----------
 * باید هر دو جهت تازه بماند: محصولی که همین حالا از پنل اضافه شده نباید
 * نیم‌دقیقه ۴۱۰ بگیرد، و محصولی که حذف شده نباید نیم‌دقیقه با ۲۰۰ سرو شود.
 * ۶۰ ثانیه همان عددی است که `revalidate` خودِ صفحه‌ی محصول هم دارد
 * (`app/product/[id]/page.tsx`)، پس هیچ‌وقت کندتر از خودِ صفحه تازه نمی‌شود.
 *
 * ---------- چرا سقفِ تعداد ----------
 * `Map` در محیطِ Edge عمرِ نامعلومی دارد و کلیدش از URLِ کاربر می‌آید؛ بدونِ
 * سقف، یک اسکنرِ ساده با میلیون‌ها شناسه می‌تواند حافظه را پر کند. وقتی به
 * سقف رسیدیم کلِ کش پاک می‌شود (نه LRUِ پیچیده): هزینه‌ی اشتباهش یک درخواستِ
 * اضافه است، نه یک باگ.
 */
export function createExistenceCache(
  ttlMs = 60_000,
  maxEntries = 500,
): ExistenceCache {
  const map = new Map<string, { exists: boolean; at: number }>();
  return {
    get(id, now = Date.now()) {
      const hit = map.get(id);
      if (!hit) return undefined;
      if (now - hit.at >= ttlMs) {
        map.delete(id);
        return undefined;
      }
      return hit.exists;
    },
    set(id, exists, now = Date.now()) {
      if (map.size >= maxEntries) map.clear();
      map.set(id, { exists, at: now });
    },
    size: () => map.size,
    clear: () => map.clear(),
  };
}
