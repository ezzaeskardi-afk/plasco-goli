// ============================================================
// سالِ جاری در تقویمِ هجریِ شمسی — برای پاورقی
// ============================================================
// این تابع یک تصمیمِ آگاهانه را ثبت می‌کند که با نسخه‌ی Express **فرق دارد** و
// دلیلش را باید بدانید:
//
// نسخه‌ی Express این بود (common.js:373):
//
//     el.textContent = `© ${new Date().getFullYear()} پلاسکو گلی. تمامی حقوق محفوظ است.`
//
// یعنی سالِ **میلادی** با رقم‌های لاتین (مثلاً «© 2026»). برای فروشگاهی که همه‌ی
// عددهای دیگرش (قیمت، تعداد، شماره‌ی سفارش) فارسی است، این یک ناهماهنگی بود.
// اینجا همان «تازه بماند» حفظ می‌شود (سال هرگز در کد ثابت نمی‌شود) ولی تقویم و
// رقم‌ها درست‌اند: «۱۴۰۵».
//
// چرا `Intl` و نه محاسبه‌ی دستیِ تقویم: تبدیلِ میلادی به شمسی الگوریتمِ حساسی
// دارد (کبیسه‌ی ۳۳ساله) و یک اشتباهِ کوچک یعنی پاورقی یک سال عقب/جلو. موتورِ
// `Intl` همان چیزی است که همه‌ی مرورگرها و Node استفاده می‌کنند و سنجیده شد که
// `fa-IR` پیش‌فرض هم تقویمِ شمسی و رقم‌های فارسی می‌دهد:
//
//     new Intl.DateTimeFormat('fa-IR', { year: 'numeric' }).format(new Date())  →  «۱۴۰۵»

/** سالِ هجریِ شمسی با رقم‌های فارسی، مثلاً «۱۴۰۵». */
export function jalaliYear(date: Date = new Date()): string {
  return new Intl.DateTimeFormat("fa-IR", { year: "numeric" }).format(date);
}

/**
 * متنِ کاملِ پاورقی — عیناً همان جمله‌ی Express، فقط با سالِ درست.
 *
 * نقطه‌گذاری هم مثلِ Express است (نقطه پس از «پلاسکو گلی»، نه خطِ تیره):
 * `common.js:375` → «© 2026 پلاسکو گلی. تمامی حقوق محفوظ است.» پس تنها
 * تفاوتِ باقی‌مانده، تقویم/رقمِ سال است که حذفش عمدی نیست بلکه خواسته است.
 */
export function footerNotice(date: Date = new Date()): string {
  return `© ${jalaliYear(date)} پلاسکو گلی. تمامی حقوق محفوظ است.`;
}
