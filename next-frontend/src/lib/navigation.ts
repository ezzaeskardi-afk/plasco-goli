// ============================================================
// ناوبری‌های «راهِ فرار» — همان‌هایی که مرورگر خودش اجرا می‌کند
// ============================================================
// چرا این فایل وجود دارد: ناوبریِ نرمِ App Router (`router.push`) یک وعده‌ی
// نرم است — اگر درخواستِ RSC هیچ‌وقت پاسخ نگیرد، کاربر روی اسکلتونِ بارگذاری
// می‌ماند و **هیچ راهی برای بیرون آمدن ندارد**: نه پیامی، نه دکمه‌ای، نه
// لینکی. کد بالا دست نمی‌تواند آن وعده را لغو کند، ولی می‌تواند بعد از چند
// ثانیه به ناوبریِ کاملِ مرورگر سوئیچ کند:
//
//   • آدرس همان آدرسِ مقصد است (روتر Next آدرس را همان لحظه‌ی push عوض می‌کند)،
//     پس بارگذاریِ دوباره دقیقاً همان صفحه‌ای را می‌آورد که کاربر منتظرش بود.
//   • نوارِ پیشرفتِ خودِ مرورگر دیده می‌شود — «گیر کردن» دیگر بی‌صدا نیست.
//   • صفحه‌ی مقصد از صفر رندر می‌شود، بدونِ هیچ حالتِ معلّقِ روتر.
//
// این دو تابع عمداً در یک ماژولِ جدا هستند و نه درونِ کامپوننت‌ها: آزمونِ
// واحد نمی‌تواند `window.location` را در jsdom جعل کند (نه قابلِ‌نوشتن است نه
// قابلِ‌حذف)، پس مرزِ این دو کار در یک جا جمع شده تا آزمون‌ها همین ماژول را
// جعل کنند و رفتارِ دیده‌شده‌ی کاربر را بسنجند.

/** ناوبریِ کاملِ مرورگر — از سوراخِ «گیر کردن» بیرون می‌آورد. */
export function hardNavigate(url: string): void {
  window.location.assign(url);
}

/** بارگذاریِ دوباره‌ی همان آدرسِ فعلی. */
export function reloadPage(): void {
  window.location.reload();
}
