// ============================================================
// نرمال‌سازیِ متن فارسی برای جستجوی سمتِ کلاینت
// ============================================================
// اینجا سرور در دسترس نیست. جستجوی فروشگاه (صفحه‌ی محصولات) سمتِ Express
// انجام می‌شود و آن‌جا `FOLD_MAP` در lib/db.js کارِ تاشدنِ هم‌آواها را می‌کند.
// ولی چند نمای پنل — مشتری‌ها، انبار — کلِ فهرست را یک‌جا می‌گیرند و جستجو
// روی همان مجموعه در مرورگر انجام می‌شود. پس این قواعد باید یک جا تعریف شوند
// و تست داشته باشند، وگرنه هر نما یک نسخه‌ی ناقص از خودش را می‌سازد.

/**
 * همان کاری که `PG.normFa` در پنلِ Express می‌کند: ي/ى عربی → ی، ك عربی → ک،
 * نیم‌فاصله → فاصله، فاصله‌های تکراری یکی، حروف کوچک.
 *
 * بدونِ این، «مهدي» (با ي عربی) مشتریِ «مهدی» را پیدا نمی‌کند — و چون
 * صفحه‌کلیدهای فارسی هر دو شکل را تولید می‌کنند، این یک تفاوتِ ظاهری نیست.
 */
export function normFa(s: string): string {
  return String(s || "")
    .replace(/[يى]/g, "ی")
    .replace(/ك/g, "ک")
    .replace(/\u200c/g, " ")
    .replace(/\s+/g, " ")
    .trim()
    .toLowerCase();
}

/**
 * ارقامِ فارسی (۰-۹) و عربی (٠-٩) → لاتین.
 *
 * ⚠️ اینجا از پنلِ Express **جلوتر** است و عمداً: `PG.normFa` ارقام را تبدیل
 * نمی‌کند، پس در آن پنل جستجوی «۰۹۱۲…» (با ارقامِ فارسی) هیچ نتیجه‌ای نمی‌دهد،
 * در حالی که شماره‌ها در دیتابیس لاتین ذخیره شده‌اند. مدیر روی صفحه‌کلیدِ فارسی
 * همان لحظه به نتیجه‌ی خالی می‌رسد و فکر می‌کند مشتری ثبت نشده است.
 *
 * جهتِ تفاوت مهم است: این تابع جستجو را «بازتر» می‌کند، نه تنگ‌تر — پس در
 * دوره‌ای که هر دو پنل زنده‌اند، این یکی هر چه آن یکی پیدا می‌کند پیدا می‌کند
 * به‌اضافه‌ی مواردی که با ارقامِ فارسی تایپ شده‌اند.
 */
export function foldDigits(s: string): string {
  return String(s || "").replace(/[\u06F0-\u06F9\u0660-\u0669]/g, (c) => {
    const code = c.charCodeAt(0);
    const base = code >= 0x06f0 ? 0x06f0 : 0x0660;
    return String(code - base);
  });
}

/**
 * گامِ اولِ کلیدِ مقایسه: ارقام لاتین، بعد متن نرمال.
 *
 * ترتیب مهم است — اول ارقام، بعد متن — تا طرفِ پرس‌وجو و طرفِ داده دقیقاً یک
 * مسیر را طی کنند. اگر یکی از دو طرف یک مرحله را جا بیندازد، تفاوتش فقط با
 * ارقامِ فارسی و نام‌های عربی‌نویس خودش را نشان می‌دهد، یعنی جایی که کسی
 * دنبالش نمی‌گردد.
 */
export function searchFold(s: string): string {
  return normFa(foldDigits(s));
}

/**
 * کلیدِ نهاییِ مقایسه: **بدونِ هیچ فاصله‌ای**.
 *
 * چرا فاصله‌ها کامل حذف می‌شوند و فقط به یک فاصله تبدیل نمی‌شوند: در فارسی
 * «فاصله»، «نیم‌فاصله» و «هیچ» هر سه به‌جای هم می‌آیند و آدم‌ها هم هر سه را
 * می‌نویسند — «میرحسینی»، «میر‌حسینی» و «میر حسینی» یک نام‌اند. با تنها
 * نرمال‌سازی، دو تای اول به «میر حسینی» می‌رسند ولی سومی به «میرحسینی» و
 * جستجوی «میرحسینی» او را پیدا نمی‌کند. برای شماره هم همین‌طور است:
 * «۰۹۱۲ ۳۴۵ ۶۷۸۹» و «09123456789» یک شماره‌اند.
 *
 * این تابع فقط یک کلیدِ داخلی است و برای نمایش ساخته نشده — خروجی‌اش عمداً
 * فاصله ندارد. برای نمایش همان `normFa` درست است.
 */
export function compareKey(s: string): string {
  return searchFold(s).replace(/\s+/g, "");
}

/**
 * «آیا این رکورد با پرس‌وجو می‌خواند؟» — پرس‌وجوی خالی همه‌چیز را می‌خواند.
 *
 * یک قاعده برای همه‌ی نماها: زیررشته، بی‌توجه به بزرگیِ حروف، بی‌توجه به شکلِ
 * ارقام، بی‌توجه به فاصله/نیم‌فاصله. همه‌ی این‌ها فقط شرطِ تطبیق را بازتر
 * می‌کند، هیچ‌وقت تنگ‌تر — یعنی هیچ موردی که قبلاً پیدا می‌شد گم نمی‌شود.
 */
export function matchesQuery(query: string, ...fields: string[]): boolean {
  const q = compareKey(query);
  if (!q) return true;
  return compareKey(fields.join(" ")).includes(q);
}
