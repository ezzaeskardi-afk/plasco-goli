// این اعداد عمداً از کامپوننت بیرون‌اند تا سنجیدنی باشند. تفاوتِ نسخه‌ی Next با
// Express اینجا پنهان بود: هیچ‌کدام از این سه جلوه در Next وجود نداشت، یعنی
//   • هدر بعد از اسکرول سایه/زمینه‌ی تیره‌تر نمی‌گرفت (متنی که روی هیرو
//     می‌لغزید کم‌کنتراست می‌شد)،
//   • دکمه‌ی «بازگشت به بالا» نبود، پس در صفحه‌های بلندِ موبایل مشتری باید
//     کیلومتر اسکرول می‌کرد تا به منو برسد،
//   • و `[data-reveal]` بدونِ ناظر، **محتوا را نامرئی می‌گذاشت** (`opacity:0`
//     در CSS)، چون کسی نبود که `is-visible` را بگذارد. یعنی هر صفحه‌ای که
//     این نشانه را داشت، بخشیش خالی دیده می‌شد.
//
// عددها حرف‌به‌حرف همان‌های common.js:379 و common.js:407 هستند.

/** از این ارتفاع به بعد هدر «چسبیده» حساب می‌شود (نه صفر: با ۱px اسکرول هم یک لرزش کوچک می‌دهد). */
export const HEADER_SCROLLED_AT = 10;

/** از این ارتفاع به بعد دکمه‌ی بازگشت به بالا نمایان می‌شود. */
export const TO_TOP_AT = 600;

/** چه کسری از المان باید دیده شود تا «وارد دید شد» حساب شود. */
export const REVEAL_THRESHOLD = 0.12;

/** تأخیرِ پله‌ای بین همسایه‌ها. */
export const REVEAL_STEP_MS = 80;

/**
 * سقفِ پله‌ها. ۴ پله یعنی حداکثر ۳۲۰ms تأخیر. بدونِ سقف، در یک لیستِ ۲۰ کارتی
 * آخرین کارت ۱٫۵ ثانیه بعد ظاهر می‌شد و حسِ کندی می‌داد.
 */
export const REVEAL_MAX_STEPS = 4;

/**
 * تأخیرِ پله‌ای برای نُهمین المانِ یک والد.
 *
 * ترتیبِ ورودی همان ترتیبِ DOM است و شمارش **per-parent** است: کارت‌های یک
 * گرید پشت‌سرهم می‌آیند، ولی گریدِ بعدی از صفر شروع می‌کند — وگرنه صفحه‌ی
 * بلند آخرش پله‌پله‌ی بی‌پایان می‌شد.
 */
export function staggerDelayMs(index: number): number {
  return Math.min(index, REVEAL_MAX_STEPS) * REVEAL_STEP_MS;
}
