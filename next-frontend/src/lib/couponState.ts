// ============================================================
// وضعیتِ واقعیِ یک کد تخفیف
// ============================================================
// در دیتابیس `active` فقط یک پرچمِ دستی است. کدی که «فعال» است می‌تواند
// منقضی شده باشد یا ظرفیتش پر شده باشد؛ مشتری آن را در سبد می‌زند و
// «این کد تخفیف معتبر نیست» می‌گیرد در حالی که پنل کد را فعال نشان می‌دهد.
//
// این قاعده در **دو** نما لازم است و برای همین اینجاست و نه داخل یکی از آن‌ها:
//
//   • نمای «تخفیف‌ها» — برچسبِ هر ردیف و شمارشِ «کدهای فعالی که کار نمی‌کنند»
//   • نمای «تنظیمات» — وقتی روی بنرِ جشنواره کدی نوشته می‌شود، همان لحظه باید
//     معلوم شود که آن کد واقعاً کار می‌کند یا نه. بنرِ صفحه‌ی اصلی به مشتری
//     تخفیف وعده می‌دهد؛ اگر کدش مرده باشد، وعده‌ی دروغ است.
//
// دو نسخه‌ی جدا از این قاعده یعنی دو پنل می‌توانند یک کد را دو چیز بنامند —
// و دقیقاً همان چیزی است که این مهاجرت می‌خواهد جمعش کند.

import type { Coupon } from "./adminTypes";

export type CouponState = "live" | "inactive" | "expired" | "exhausted";

/** برچسبِ فارسیِ هر وضعیت — رنگش کارِ UI است، نه اینجا */
export const COUPON_STATE_LABEL: Record<CouponState, string> = {
  live: "کار می‌کند",
  inactive: "خاموش",
  expired: "منقضی شده",
  exhausted: "ظرفیت پر شده",
};

/** تاریخِ محلی به شکل YYYY-MM-DD — همان چیزی که سرور با `date('now','localtime')` می‌سازد */
export function localToday(now = new Date()): string {
  return `${now.getFullYear()}-${String(now.getMonth() + 1).padStart(2, "0")}-${String(
    now.getDate(),
  ).padStart(2, "0")}`;
}

/**
 * وضعیتِ واقعیِ کد — بازسازیِ ترتیبِ بررسی‌های `quoteCoupon` (lib/db.js:2235).
 *
 * ترتیب مهم است: کدِ خاموشی که هم منقضی است و هم ظرفیتش پر، «خاموش» گزارش
 * می‌شود، چون تنها کاری که مدیر باید بکند روشن‌کردنش نیست — اول باید بفهمد
 * چرا کار نمی‌کند. اگر برچسبِ «منقضی» می‌گرفت، روشنش می‌کرد و باز هم کار
 * نمی‌کرد.
 *
 * یک قاعده‌ی `quoteCoupon` عمداً اینجا نیست: **سقفِ هر مشتری**. آن قاعده به
 * مشتری بستگی دارد، نه به کد؛ کدی که یک نفر ظرفیتش را پر کرده برای بقیه هنوز
 * کار می‌کند. پس این وضعیت نمی‌تواند و نباید بر اساسش عوض شود.
 *
 * `minTotal` هم همین‌طور: کدی با حداقلِ خریدِ بالا خراب نیست، فقط روی سبدهای
 * کوچک اثر ندارد.
 */
export function couponStateOf(c: Coupon, today = localToday()): CouponState {
  if (!c.active) return "inactive";
  // مقایسه‌ی رشته‌ای، عیناً مثل سرور: `c.expires_at < today`. یعنی کدی که
  // امروز منقضی می‌شود هنوز تا آخرِ امروز معتبر است.
  if (c.expiresAt && c.expiresAt < today) return "expired";
  if (c.usageLimit > 0 && c.uses >= c.usageLimit) return "exhausted";
  return "live";
}

// عمداً هیچ تابعِ *قالب‌بندی* (تومان/عدد فارسی) اینجا نیست: این ماژول قاعده
// است، نه نمایش. هر نما با ابزارهای خودش قالب می‌بندد و اگر قالب‌بندی اینجا
// بیاید، ماژول باید به کامپوننتی وابسته شود که آن هم «use client» است —
// یعنی قاعده‌ی مشترک به یک مرزِ کلاینت گره می‌خورد.
