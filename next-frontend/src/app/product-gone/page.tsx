import type { Metadata } from "next";
import { ProductGone } from "@/components/ProductGone";

// ============================================================
// صفحه‌ی «محصول حذف شد» — همان بدنه‌ای که middleware با کدِ ۴۱۰ می‌فرستد
// ============================================================
// ---------- چرا این مسیر وجود دارد ----------
// در App Router کدِ HTTP را نمی‌شود از داخلِ `page.tsx` یا `not-found.tsx`
// عوض کرد، و `/product/[id]` هم به‌خاطرِ ISR پاسخِ `notFound()` را با **۲۰۰**
// کش می‌کند. پس `middleware.ts` وقتی می‌فهمد شناسه محصول ندارد، بدنه‌ی همین
// صفحه را می‌گیرد و با کدِ **۴۱۰** برمی‌گرداند — همان کاری که Express در
// `server.js:526` می‌کند.
//
// ---------- چرا از خودِ مسیر محصول واکشی نمی‌کند ----------
// اگر middleware همان `/product/999999` را دوباره واکشی می‌کرد، آن درخواست هم
// از middleware می‌گذشت و زنجیره می‌شد؛ جلوگیری‌اش هم به یک هدرِ نشانه‌گذاری
// یا توکنِ مخفی نیاز داشت که در نصبِ چند‌پروسه‌ای (cluster) قابلِ اتکا نیست.
// این مسیر خارج از الگوی `/product/:id` است، پس هیچ حلقه‌ای ممکن نیست.
//
// ---------- این آدرس مثلِ خودِ Express عمومی است ----------
// نسخه‌ی Express هم `/product-gone.html` را با کدِ ۲۰۰ سرو می‌کند؛ اینجا هم
// همین کار را می‌کنیم و تنها محافظتش `noindex` است. هیچ لینکی به این‌جا
// اشاره نمی‌کند؛ فقط middleware بدنه‌اش را برمی‌دارد.

export const metadata: Metadata = {
  // قالبِ ریشه («%s | پلاسکو گلی») همین را به عنوانِ کاملِ Express می‌رساند:
  // «این محصول دیگر موجود نیست | پلاسکو گلی»
  title: "این محصول دیگر موجود نیست",
  // یک تگ، به‌جای دوتای فعلی؛ Express هم فقط همین یکی را داشت.
  robots: { index: false, follow: true },
};

export default function ProductGonePage() {
  return <ProductGone />;
}
