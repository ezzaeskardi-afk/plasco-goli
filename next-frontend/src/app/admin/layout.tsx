import type { Metadata } from "next";
import { headers } from "next/headers";
import { AdminNav } from "@/components/AdminNav";
import { ADMIN_SECTIONS, PENDING_SECTIONS, READY_SECTIONS } from "@/lib/adminSections";
import {
  NoAccess,
  type PanelAccess,
  type PanelRole,
} from "@/components/admin/NoAccess";

// ============================================================
// پوسته‌ی مشترکِ پنل مدیریت
// ============================================================
// این فایل قبلاً وجود نداشت و تنها صفحه‌ی پنل، `admin/crm/page.tsx` بود. بدونِ
// پوسته، هر نمای تازه باید نوارِ ناوبریِ خودش را می‌ساخت و اولین چیزی که از
// دست می‌رفت همین بود: «بقیه‌ی بخش‌ها کجاست؟»
//
// `robots: { index: false }` اینجا گذاشته شده نه در هر صفحه: هر صفحه‌ای که
// روزی زیر `/admin` اضافه شود، به‌طور پیش‌فرض از ایندکس بیرون می‌ماند. فراموش
// کردنش در یک صفحه یعنی یک صفحه‌ی داخلیِ پنل در گوگل.
//
// `follow: false` هم عمدی است: از پنل نباید هیچ ارزش لینکی به بیرون رد شود.
//
// ⚠️ نکته‌ای که یک‌بار ما را گرفت: متادیتای فرزند فیلد `robots` را **کامل**
// جایگزین می‌کند، نه اینکه با والد ادغام شود. پس اگر صفحه‌ای زیرِ /admin
// دوباره `robots` بنویسد، `follow: false` بی‌صدا از دست می‌رود. به همین دلیل
// `admin/crm/page.tsx` دیگر `robots` خودش را ندارد. صفحه‌های تازه هم نباید
// داشته باشند — فقط `title`.
//
// ============================================================
// دروازه‌ی نمایشیِ پنل
// ============================================================
// این پوسته **هیچ‌کاری با مجوز نمی‌کند**: نه چیزی را باز می‌کند و نه می‌بندد.
// سدِ واقعی سمتِ Express است (`routes/admin.js:68`) و هر درخواستِ API مستقیماً
// به آن می‌رسد؛ پس نمی‌شود از اینجا دورش زد.
//
// کاری که اینجا می‌شود: **نوارِ پنل را به کسی که مالکش نیست نشان ندادن.**
// تصمیمش در `middleware.ts` گرفته شده (چون آنجا هم مسیرِ جاری را دارد و هم
// نقشِ کاربر را از همان `/api/auth/me`‌یی که برای نگهبانی می‌زد) و به‌صورت
// هدرهای `x-panel-*` به اینجا رسیده. اینجا فقط خوانده و رندر می‌شود — پس
// قاعده‌ی دسترسی در یک جا است، نه دو جا.
//
// اگر هدر نبود (`unknown`) پنل رندر می‌شود، یعنی رفتارِ قبلی. دلیلش این است که
// این هدرها یک *راهنمای نمایشی*‌اند و نه مرزِ امنیتی: فرضِ اشتباه در جهت
// «پنل را نشان بده» بدترین نتیجه‌اش یک کادرِ ۴۰۳ِ سمتِ سرور است، ولی فرضِ
// اشتباه در جهتِ دیگر یعنی مدیرِ واقعی پنلش را نمی‌بیند و دنبالِ باگ می‌گردد.

export const metadata: Metadata = {
  robots: { index: false, follow: false },
};

export default async function AdminLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const h = await headers();
  const access = (h.get("x-panel-access") ?? "unknown") as PanelAccess;
  const role = (h.get("x-panel-role") ?? "unknown") as PanelRole;
  const phone = h.get("x-panel-phone") ?? "";

  // «orders» یعنی کارمندی که فقط اجازه‌ی بخشِ سفارش‌ها را دارد و الان همان
  // جاست — برای او پنل رندر می‌شود.
  if (access === "none") {
    return (
      <div style={{ background: "var(--color-cream)", minHeight: "60vh" }}>
        <NoAccess role={role} phone={phone} />
      </div>
    );
  }

  return (
    <div style={{ background: "var(--color-cream)" }}>
      <AdminNav role={role} />
      {children}

      {/* پانویسِ وضعیتِ مهاجرت.

          عمداً اینجاست و نه در داشبورد: شمارشِ «چند بخش منتقل شده» اطلاعاتِ
          وضعیتِ پروژه است، نه کاری که مدیر برای فروش کند. ولی پنهان‌کردنش هم
          غلط است: مدیر باید بداند چرا ۸ بخش در نوار خاکستری‌اند و کجا پیدایشان
          کند. عددها از `adminSections.ts` می‌آیند، پس با منتقل‌شدنِ هر نما خودش
          به‌روز می‌شود و روزی که همه منتقل شوند، کلِ این بلوک ناپدید می‌شود. */}
      {/* برای کارمند نشان داده نمی‌شود: او فقط به سفارش‌ها راه دارد، پس این
          جمله که «۸ بخش منتقل شده و ۵ بخش در پنل Express است» برایش بی‌ربط
          است — بخش‌های Express هم اصلاً در نوارش نیستند. */}
      {role !== "staff" && PENDING_SECTIONS.length > 0 && (
        <footer className="mx-auto max-w-[1180px] px-6 pt-4 pb-10">
          <p
            className="text-[11px] leading-relaxed"
            style={{ color: "var(--color-ink-dim)" }}
          >
            {fa(READY_SECTIONS.length)} بخش از {fa(ADMIN_SECTIONS.length)} بخشِ پنل به
            نسخه‌ی Next منتقل شده است. {fa(PENDING_SECTIONS.length)} بخشِ دیگر —
            آن‌هایی که در نوارِ بالا برچسبِ «Express» دارند — هنوز در پنل قبلی
            است و همان‌جا کار می‌کند.
          </p>
        </footer>
      )}
    </div>
  );
}

/**
 * عددِ فارسی.
 *
 * چرا `faNum` از `AdminBits` وارد نمی‌شود: آن فایل `"use client"` است و همه‌ی
 * صادرهایش به «مرجعِ کلاینت» تبدیل می‌شوند. صدا زدنشان از یک کامپوننتِ سروری
 * (همین فایل) در زمان اجرا خطا می‌دهد — چون تابع دیگر روی سرور وجود ندارد.
 * چهار خطِ Intl از یک خطای زمانِ اجرا بهتر است.
 */
function fa(n: number): string {
  return new Intl.NumberFormat("fa-IR").format(n);
}
