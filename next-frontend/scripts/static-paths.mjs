// چرا استخراج شد: این فهرست + منطقِ کشفش تا امروز *داخل* اجراکنندهٔ زنده بود.
// یعنی نگهبانِ `src/app/staticPathsCoverage.test.ts` (که می‌سنجد «هر ارجاعِ
// سورس سنجیده می‌شود؟») راهی نداشت جز regex‌زدن به متنِ همان اسکریپت — و
// آن‌وقت فهرست دو جا زندگی می‌کرد و اولین تغییرِ یکی، سنجشِ دیگری را بی‌ربط
// می‌کرد. حالا هر دو یک ماژول را import می‌کنند: بدونِ کپی، بدونِ واگرایی.
//
// هر ردیفِ فهرست یک **دلیل** دارد؛ دلیلِ خالی یعنی «نمی‌دانیم چرا اینجاست» و
// آزمون همان را قرمز می‌کند. و حذفِ یک ردیف هم بی‌صدا نیست: اگر آن مسیر جایی
// ارجاع داشته باشد، آزمونِ پوشش می‌گوید «ارجاع دارد ولی سنجیده نمی‌شود».

import fs from "node:fs";

