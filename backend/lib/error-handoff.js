/* ============================================================
   خطاها صفحه‌ی این سرور نیستند — تصمیمِ «کجا برود» در یک جا

   ---------- چرا این فایل وجود دارد ----------
   تا عصرِ `frontend/`، این سرور خودش دو صفحه‌ی خطا داشت: `404.html` و
   `500.html`. هر دو حذف شدند و معادل‌هایشان در Next است (`app/not-found.tsx`
   و `app/error.tsx` + `app/global-error.tsx`) — ولی *خودِ پاسخِ خطا* همچنان
   از این‌جا می‌آمد: متنِ ساده‌ی «چنین صفحه‌ای وجود ندارد.» و «خطای داخلی
   سرور…». یعنی روی همان دامنه، دو جور خطا دیده می‌شد: صفحه‌ی استایل‌دارِ Next
   برای مسیرهایی که به Next می‌رسند، و یک تکه متنِ بی‌استایل برای مسیرهایی که
   به این سرور می‌رسند. دومی باقی‌مانده‌ی دنیای قدیم بود.

   قاعده‌ای که این‌جا نوشته شده همان قاعده‌ی `/admin` و `/?product/:id` است
   (server.js): **صفحه‌های Next روی دامنه‌ی خودشان سرو می‌شوند؛ این سرور فقط
   نگاشت می‌کند.** پس خطا هم اگر صفحه‌شکل باشد، ۳۰۲ به همان مسیر روی سایت
   می‌رود و کاربر صفحه‌ی استایل‌دارِ Next را می‌بیند — نه یک متنِ خالی.
   (۳۰۲ و نه ۳۰۱: مسیری که امروز نیست ممکن است فردا باشد و مرورگر نباید
   نسخه‌ی «نیست» را برای همیشه کش کند.)

   مهم: این ماژول **تصمیم** می‌گیرد، پاسخ نمی‌فرستد. یک تابعِ خالص است تا
   بتوان بی‌سرور و بی‌دیتابیس آزمودش (`tests/error-handoff.js`) — همان
   الگوی `lib/legacy-redirects.js`.

   ---------- چهار حالت، و دلیلِ هر کدام ----------
     api        `/api/*` → JSON. مصرف‌کننده‌ی این مسیرها `fetch()` است، نه یک
                تبِ مرورگر؛ ۳۰۲ برای چنین کلاینتی یعنی «پاسخِ خراب» (بدنه‌ی
                JSON با کدِ ۳۰۰) و هر `res.ok` بی‌دلیل false می‌شود.
     asset      `/picture/*` → عکس، نه صفحه. اینجا ۳۰۲ **حلقه‌ی بی‌پایان**
                می‌سازد: `next.config.ts` همین `/picture/*` را دوباره به همین
                سرور پروکسی می‌کند، پس Next عکس را برمی‌گرداند به ما و ما
                برمی‌گردانیم به Next. (این تنها مسیرِ پروکسی‌شده‌ی مبدأِ Next
                است که کنارِ `/api` می‌ماند.)
     storefront صفحه‌شکل و سایت روی میزبانِ دیگری → ۳۰۲ به همان مسیر و همان
                کوئری روی سایت. کاربر یا صفحه‌ی درست را می‌بیند (و ۴۰۴ِ
                دروغینِ امروز — مثلِ `/cart` روی مبدأِ Express — برطرف
                می‌شود)، یا `not-found.tsx`ِ استایل‌دار را.
     plain      بقیه: متدِ نوشتاری، یا سایت روی همین میزبان، یا `SITE_URL`
                تنظیم‌نشده. این‌جا چیزی برای ۳۰۲‌کردن نیست (۳۰۲ به خودمان =
                همان حلقه‌ای که قاعده‌ی `/admin` با `sameHost` بست) و متدِ
                نوشتاری هم با ۳۰۲ به GET تبدیل می‌شود، یعنی تلقینِ «دوباره
                فرستاده شد». پاسخِ درست، کمینه‌ترین چیز است: متنِ ساده — نه
                یک صفحه‌ی HTMLِ دوم. (روی دامنه‌ی واحد این شاخه اصلاً دیده
                نمی‌شود: پروکسی هر مسیرِ غیرِ `/api` و غیرِ `/picture` را به
                Next می‌دهد و این سرور فقط با همان دو پیشوند کار دارد.)
   ============================================================ */
'use strict';

/** حالت‌های مجازِ تصمیم. بسته است؛ حالتِ تازه یعنی ویرایشِ همین فایل و آزمونش. */
const KINDS = ['api', 'asset', 'storefront', 'plain'];

/** متدهایی که «صفحه‌دیدن» هستند و ۳۰۲ برایشان معنا دارد. */
const PAGE_METHODS = ['GET', 'HEAD'];

/**
 * آیا سایت روی همین میزبانی است که درخواست به ما رسیده؟
 *
 * `true` یعنی «۳۰۲ به خودمان» و باید کنار گذاشته شود. `SITE_URL`ِ نامعتبر یا
 * خالی هم `true` می‌دهد: نبودِ مقصد، مقصدِ سالم نیست.
 */
function sameHost(siteUrl, host) {
  try {
    return new URL(siteUrl).host === String(host || '');
  } catch (e) {
    return true;
  }
}

/**
 * تصمیمِ «این خطا کجا پاسخ داده شود».
 *
 * @param {object} req
 * @param {string} req.method       متدِ درخواست (`GET`، `POST`، …)
 * @param {string} req.path         مسیرِ بدونِ کوئری (`req.path`)
 * @param {string} [req.originalUrl] مسیرِ کامل با کوئری (پیش‌فرض: خودِ path)
 * @param {string} [req.host]       میزبانِ درخواست (`req.get('host')`)
 * @param {string} [req.siteUrl]    پایه‌ی سایت (`siteBase(req)`)
 * @returns {{kind: string, status?: number, target?: string, why: string}}
 */
function decideErrorHandoff(req) {
  const { method, path, host, siteUrl } = req || {};
  const pathname = String(path || '/');
  const verb = String(method || 'GET').toUpperCase();

  if (pathname === '/api' || pathname.startsWith('/api/')) {
    return {
      kind: 'api',
      why: 'کلاینتِ این مسیر fetch است؛ پاسخِ خطا باید JSON با همان کد باشد',
    };
  }

  if (pathname === '/picture' || pathname.startsWith('/picture/')) {
    return {
      kind: 'asset',
      why:
        'عکس است نه صفحه، و Next همین پیشوند را به این سرور پروکسی می‌کند — ' +
        '۳۰۲ اینجا حلقه‌ی بی‌پایان می‌سازد',
    };
  }

  if (!PAGE_METHODS.includes(verb)) {
    return {
      kind: 'plain',
      why: `متدِ ${verb} نوشتاری است؛ ۳۰۲ آن را به GET تبدیل می‌کند و تلقینِ «دوباره فرستاده شد» می‌سازد`,
    };
  }

  const base = String(siteUrl || '').replace(/\/+$/, '');
  if (!base || sameHost(base, host)) {
    return {
      kind: 'plain',
      why: 'مقصدی جز همین مبدأ نیست؛ ۳۰۲ به خودمان حلقه می‌سازد',
    };
  }

  const original = String(req.originalUrl || pathname);
  return {
    kind: 'storefront',
    status: 302,
    target: base + original,
    why: 'صفحه‌ی خطا صاحب دارد (Next) و روی همان دامنه سرو می‌شود',
  };
}

module.exports = { decideErrorHandoff, KINDS, PAGE_METHODS, sameHost };
