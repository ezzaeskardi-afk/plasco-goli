'use strict';

const fs = require('fs');
const path = require('path');

const SHARED = path.join(__dirname, '..', '..', 'next-frontend', 'src', 'lib', 'legacyUrls.js');

if (!fs.existsSync(SHARED)) {
  console.error('\n' + '='.repeat(72));
  console.error('  [FATAL] تنها منبعِ حقیقتِ نشانی‌های .html پیدا نشد:');
  console.error(`          ${SHARED}`);
  console.error('  بدونش هر نشانیِ عصرِ Express روی این سرور ۴۰۴ می‌شود.');
  console.error('  (این پروژه یک مخزنِ واحد است؛ فایلِ frontend را جابه‌جا نکنید.)');
  console.error('='.repeat(72) + '\n');
  throw new Error('missing next-frontend/src/lib/legacyUrls.js');
}

module.exports = require(SHARED);
