// ---------- ساختنِ لیستِ نهایی ----------
function build() {
  const out = [];
  for (const [category, rows] of Object.entries(DATA)) {
    for (const [title, price, stock, icon, off, badge, description, ownSpecs] of rows) {
      // قیمتِ قبل از تخفیف را از درصد می‌سازیم و به هزار تومان رُند می‌کنیم،
      // چون قیمتِ ۲۸۴٬۰۹۰ تومان در پلاسکو وجود ندارد و جعلی به نظر می‌رسد.
      const old_price = off ? Math.round((price / (1 - off / 100)) / 1000) * 1000 : 0;
      out.push({
        category, title, description, price, old_price, stock, icon, badge,
        image: null, images: [],
        specs: [...ownSpecs, ...(CAT_SPECS[category] || []), ...COMMON_SPECS],
        published: 0, import_batch: BATCH
      });
    }
  }
  return out;
}

// ---------- اجرا ----------
function main() {
  const args = process.argv.slice(2);
  const dry = args.includes('--dry-run');
  const rollback = args.includes('--rollback');
  const force = args.includes('--force');

  const db = require('../lib/db');
  const items = build();

  const existing = db.getDraftSummary().batches.find(b => b.batch === BATCH);
  const have = existing ? existing.n : 0;

  if (rollback) {
    if (!have) { console.log(`Nothing to roll back: batch "${BATCH}" is not in the database.`); return; }
    const sold = db.batchHasOrders(BATCH);
    if (sold) {
      console.log(`REFUSED: ${sold} product(s) in batch "${BATCH}" already appear in orders.`);
      console.log('Deleting them would break order history. Unpublish them instead.');
      process.exitCode = 1; return;
    }
    const n = db.deleteBatch(BATCH);
    console.log(`Rolled back: ${n} product(s) removed. Catalog is now ${db.getProducts().length}.`);
    return;
  }

  if (have && !force) {
    console.log(`Batch "${BATCH}" already exists with ${have} product(s). Nothing to do.`);
    console.log('Use --rollback to remove it, or --force to add another copy (not recommended).');
    return;
  }

  console.log(`Plan: insert ${items.length} DRAFT products (published = 0), batch "${BATCH}".`);
  const byCat = {};
  for (const p of items) byCat[p.category] = (byCat[p.category] || 0) + 1;
  for (const [c, n] of Object.entries(byCat)) console.log(`  ${n.toString().padStart(3)}  ${c}`);
  console.log(`  Current catalog: ${db.getProducts().length} -> after insert: ${db.getProducts().length + items.length}`);

  if (dry) { console.log('\nDry run: nothing was written.'); return; }

  let ok = 0;
  for (const p of items) {
    try { db.adminCreateProduct(p); ok++; }
    catch (e) { console.log(`  FAILED "${p.title}": ${e.message}`); }
  }
  console.log(`\nDone: ${ok}/${items.length} inserted as drafts.`);
  console.log(`Catalog total: ${db.getProducts().length}  |  visible on site: ${db.getPublicProducts().length}`);
  console.log('Next: open the admin panel, add a photo and a real price, then publish each one.');
}

main();
