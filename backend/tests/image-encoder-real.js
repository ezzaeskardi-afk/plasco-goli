#!/usr/bin/env node
/* ============================================================
   image-encoder-real.js — دروازه‌ی «با انکودرِ واقعی»

   ---------- چرا این فایل وجود دارد ----------
   `tests/image-encoder-paths.js` دو نیمه دارد:
     • نیمه‌ی «بی‌انکودر» با `PATH`ِ خالی شبیه‌سازی می‌شود و روی **هر** ماشینی
       اجرا می‌شود (پس جهش‌هایش در رجیستریِ هارنس، دامنه‌ی `backend`).
     • نیمه‌ی «با انکودر» فقط وقتی اجرا می‌شود که روی همان ماشین انکودری
       نصب باشد — و شرطش هم همین است، نه یک شبیه‌سازی.

   آن نیمه‌ی دوم جهش‌های خودش را می‌خواهد (عرضِ نسخه‌ی کوچک، نامِ خروجی،
   بزرگ‌نکردنِ عکس). جهش‌هایش را نمی‌شود در دامنه‌ی `backend` گذاشت: روی ماشینی
   که انکودر ندارد، نگهبان آن نیمه را رد می‌کند و هارنس «جهش گرفته نشد»
   می‌بیند — یعنی یک شکستِ ساختگی، درست مثلِ دامنهٔ `static` که بک‌اندِ خواب
   می‌خواهد.

   پس دامنه‌ی جدا دارد (`--scope=encoder`) و این فایل آن دامنه را به یک
   *نگهبانِ* مستقل تبدیل می‌کند: نگهبانِ اصلی را با ادعای `EXPECT_ENCODER=1`
   اجرا می‌کند و کدِ خروجش را همان‌طور می‌فرستد. نگهبانِ پوشش (`guard-anchors`)
   هم هر فایلِ آزمون را می‌خواهد، و هارنس هر فایل را فقط یک بار می‌پذیرد —
   برای همین یک فایلِ جدا لازم بود، نه دو ورودی روی یک فایل.

   اجرا: node tests/image-encoder-real.js      (انکودر لازم است: cwebp/ImageMagick/ffmpeg/Pillow)
   ============================================================ */
'use strict';

const { spawnSync } = require('child_process');
const path = require('path');

const r = spawnSync(process.execPath, [path.join(__dirname, 'image-encoder-paths.js')], {
  cwd: path.join(__dirname, '..'),
  // `stdio: 'inherit'` مهم است: خروجیِ نگهبان همان‌جا به استدویِ این پروسه
  // می‌رود، پس هارنسِ جهش دلیلِ شکست را می‌بیند (وگرنه جهش «بی‌دلیل» شمرده می‌شد).
  env: { ...process.env, EXPECT_ENCODER: '1' },
  stdio: 'inherit',
});

if (r.error) {
  console.error(`اجرای نگهبانِ مسیرهای انکودر ممکن نشد: ${r.error.message}`);
  process.exit(1);
}
process.exit(r.status === 0 ? 0 : 1);
